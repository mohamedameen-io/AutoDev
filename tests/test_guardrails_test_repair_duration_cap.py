"""C5: per-task duration cap override for corrective test-repair tasks.

Corrective test-repair tasks have ids of the form ``{phase}.c{N}`` (e.g.
``1.c2``), generated by ``corrective_parser.py``. When
``GuardrailsConfig.max_duration_s_per_test_repair_task`` is set, the enforcer
must apply that (usually tighter) cap to those tasks while ordinary tasks
(``1.1``) keep using the global ``max_duration_s_per_task``. When the field is
``None`` (the default), every task uses the global cap — byte-identical to the
pre-C5 behaviour.
"""

from __future__ import annotations

import time
from pathlib import Path

import pytest

from adapters.types import AgentInvocation
from config.schema import GuardrailsConfig
from errors import GuardrailExceededError
from guardrails.enforcer import GuardrailEnforcer


def _cfg(**kwargs) -> GuardrailsConfig:
    defaults = {
        "max_invocations_per_task": 10,
        "max_tool_calls_per_task": 10,
        "max_duration_s_per_task": 60,
        "max_diff_bytes": 1024,
    }
    defaults.update(kwargs)
    return GuardrailsConfig(**defaults)


def _inv() -> AgentInvocation:
    return AgentInvocation(role="developer", prompt="do it", cwd=Path("/tmp"))


def _age_task(enf: GuardrailEnforcer, task_id: str, seconds: float) -> None:
    """Back-date the task's start_time so ``elapsed_s`` reports ``>= seconds``.

    Mirrors how the rest of the suite would fake wall-clock — we shift
    ``start_time`` rather than sleeping.
    """
    enf._metrics[task_id].start_time = time.monotonic() - seconds


def test_corrective_task_trips_tighter_test_repair_cap() -> None:
    # Global cap is generous (600s); the test-repair cap is tight (60s).
    enf = GuardrailEnforcer(
        _cfg(max_duration_s_per_task=600, max_duration_s_per_test_repair_task=60)
    )
    enf.start_task("1.c2")
    # Age past the test-repair cap but well under the global cap.
    _age_task(enf, "1.c2", 120)
    with pytest.raises(GuardrailExceededError) as ei:
        enf.pre_invocation("1.c2", _inv())
    # Message must name the test-repair cap, not the global one.
    msg = str(ei.value)
    assert "60" in msg
    assert "test-repair" in msg or "test_repair" in msg


def test_normal_task_uses_global_cap_even_when_repair_cap_set() -> None:
    enf = GuardrailEnforcer(
        _cfg(max_duration_s_per_task=600, max_duration_s_per_test_repair_task=60)
    )
    enf.start_task("1.1")
    # Aged past the tight test-repair cap but under the global cap: must NOT trip.
    _age_task(enf, "1.1", 120)
    enf.pre_invocation("1.1", _inv())  # should not raise

    # Aged past the global cap: now it trips on the global cap.
    _age_task(enf, "1.1", 700)
    with pytest.raises(GuardrailExceededError) as ei:
        enf.pre_invocation("1.1", _inv())
    assert "600" in str(ei.value)


def test_corrective_task_under_repair_cap_does_not_trip() -> None:
    enf = GuardrailEnforcer(
        _cfg(max_duration_s_per_task=600, max_duration_s_per_test_repair_task=60)
    )
    enf.start_task("1.c2")
    _age_task(enf, "1.c2", 30)  # under the 60s test-repair cap
    enf.pre_invocation("1.c2", _inv())  # should not raise


def test_none_field_both_use_global_cap() -> None:
    # Field unset (None) — both task kinds use the global cap, byte-identical
    # to pre-C5 behaviour.
    enf = GuardrailEnforcer(
        _cfg(max_duration_s_per_task=60, max_duration_s_per_test_repair_task=None)
    )
    assert enf._eff_max_duration_s_per_test_repair_task is None

    # Corrective task: under global cap does not trip; over it does.
    enf.start_task("1.c2")
    _age_task(enf, "1.c2", 30)
    enf.pre_invocation("1.c2", _inv())  # no raise

    _age_task(enf, "1.c2", 120)
    with pytest.raises(GuardrailExceededError) as ei:
        enf.pre_invocation("1.c2", _inv())
    assert "60" in str(ei.value)

    # Normal task: same global cap.
    enf.start_task("1.1")
    _age_task(enf, "1.1", 120)
    with pytest.raises(GuardrailExceededError) as ei2:
        enf.pre_invocation("1.1", _inv())
    assert "60" in str(ei2.value)


def test_repair_cap_cached_on_construction() -> None:
    enf = GuardrailEnforcer(_cfg(max_duration_s_per_test_repair_task=90))
    assert enf._eff_max_duration_s_per_test_repair_task == 90.0


@pytest.mark.parametrize(
    "task_id, is_corrective",
    [
        ("1.c2", True),
        ("1.c10", True),
        ("12.c3", True),
        ("1.1", False),
        ("1.2", False),
        ("plan", False),
        ("1c2", False),  # no dot
        ("1.c2a", False),  # trailing char after digits
    ],
)
def test_corrective_pattern_selection(task_id: str, is_corrective: bool) -> None:
    # Tight repair cap; if the id is corrective the tighter cap fires under
    # the 120s ageing, otherwise it falls through to the generous global cap.
    enf = GuardrailEnforcer(
        _cfg(max_duration_s_per_task=600, max_duration_s_per_test_repair_task=60)
    )
    enf.start_task(task_id)
    _age_task(enf, task_id, 120)
    if is_corrective:
        with pytest.raises(GuardrailExceededError):
            enf.pre_invocation(task_id, _inv())
    else:
        enf.pre_invocation(task_id, _inv())  # under global 600s cap
